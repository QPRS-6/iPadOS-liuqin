#!/bin/bash
# Embed shim/out/libliuqintouch.dylib into the kernel tree (bsd/dev/liuqin_dylib.h).
#   tools/embed-dylib.sh [DYLIB]
set -euo pipefail
cd "$(dirname "$0")/.."
src=${1:-shim/out/libliuqintouch.dylib}
dest="${WORK:-/Users/qprs/liuqin-build3}/xnu/bsd/dev/liuqin_dylib.h"
python3 - "$src" "$dest" <<'PY'
import sys
path, dest = sys.argv[1], sys.argv[2]
data = open(path, 'rb').read()
out = ['/* Generated from %s - regenerated by tools/embed-dylib.sh. */' % path,
       '#define LIUQIN_DYLIB_BYTES %d' % len(data),
       'static const unsigned char liuqin_dylib_image[] = {']
for i in range(0, len(data), 16):
    out.append('\t' + ','.join('0x%02x' % b for b in data[i:i+16]) + ',')
out.append('};')
open(dest, 'w').write('\n'.join(out) + '\n')
print('embedded %d bytes into %s' % (len(data), dest))
PY
