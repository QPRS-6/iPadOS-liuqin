#!/usr/bin/env python3
"""Generate NativeAdrenoA730HwInit.h (a730 HWCG + CP protect tables).

Sources (both under linux-ref/):
  a730_tables.inc  the a730_hwcg[] and a730_protect_regs[] blocks copied
                   verbatim from upstream a6xx_catalog.c (GPL-2.0-only). Only
                   the register/value *facts* are transcribed here; the table
                   text itself is not.
  a730_hwcg.h      numeric dword offsets for the a730_hwcg[] names, resolved
                   once through mesa's a6xx.xml.

The protect encoding is the one upstream writes, verified bit for bit
against all 46 shared ranges of the a740 protect table: bits 0-17 the start
register, bits 18-30 the A6XX_PROTECT_*(offset, len) span, bit 31 set for the
NORDWR form and clear for RDONLY (start 0x1f8c0 needs 18 bits, every span is
<= 0x1fff, and the ranges chain: 0x18400+0x53 ends 0x18453, the next starts
0x18454).  a6xx_set_cp_protect() writes protect->regs[i] to CP_PROTECT(i)
for i < count-1, skipping zeros, then writes the last entry to
CP_PROTECT(count_max-1) == 47, so the two all-zero slots (45, 46) stay
untouched and the output keeps the original indices.

Usage: tools/gen-a730-hwinit.py [OUT]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(os.path.dirname(HERE), 'linux-ref')

HWCG_COUNT = 53          # a730_hwcg[] entries in a730_tables.inc (excludes the {} terminator)


def read_hwcg():
    """[(offset, value, name)] for a730_hwcg, in table order."""
    names = []
    with open(os.path.join(REF, 'a730_tables.inc')) as f:
        body = f.read()
    block = re.search(r'a730_hwcg\[\]\s*=\s*\{(.*?)\n\};', body, re.S).group(1)
    for line in block.splitlines():
        m = re.match(r'\s*\{\s*(REG_[A-Z0-9_]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\},', line)
        if m:
            names.append((m.group(1), int(m.group(2), 16)))
    assert len(names) == HWCG_COUNT, len(names)

    offs = []
    with open(os.path.join(REF, 'a730_hwcg.h')) as f:
        for line in f:
            m = re.match(r'\s*\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\},', line)
            if m:
                offs.append((int(m.group(1), 16), int(m.group(2), 16)))
    # a730_hwcg.h also carries a second table (the a740 list) from lines 54 on;
    # the a730 payload is exactly the first HWCG_COUNT entries, and its values
    # match a730_tables.inc entry for entry - check that instead of trusting it.
    assert len(offs) >= HWCG_COUNT, len(offs)
    out = []
    for i, (name, value) in enumerate(names):
        off, hvalue = offs[i]
        assert hvalue == value, (i, name, hex(value), hex(hvalue))
        out.append((off, value, name))
    assert len({o for o, _, _ in out}) == len(out), 'duplicate hwcg offsets'
    return out


def read_protect():
    """[(index, value, text)] with zeros preserved so indices match upstream."""
    with open(os.path.join(REF, 'a730_tables.inc')) as f:
        body = f.read()
    block = re.search(r'a730_protect_regs\[\]\s*=\s*\{(.*?)\n\};', body, re.S).group(1)
    entries = []
    for line in block.splitlines():
        line = line.strip()
        if not line or line.startswith('/*') or line.startswith('*'):
            continue
        line = re.sub(r'\s*/\*.*?\*/', '', line).strip().rstrip(',')
        if line in ('0', ''):
            entries.append(None)
            continue
        m = re.match(r'A6XX_PROTECT_(RDONLY|NORDWR)\(\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\)$', line)
        assert m, line
        kind, start, length = m.group(1), int(m.group(2), 16), int(m.group(3), 16)
        assert start <= 0x1ffff and length <= 0x1fff, (hex(start), hex(length))
        value = start | (length << 18) | (0x80000000 if kind == 'NORDWR' else 0)
        entries.append((value, line))
    assert len(entries) == 48, len(entries)      # DECLARE_ADRENO_PROTECT(a730_protect, 48)
    assert entries[45] is None and entries[46] is None
    out = [(i, v, t) for i, e in enumerate(entries) if e is not None for v, t in (e,)]
    assert len(out) == 46, len(out)
    return out


HEADER = '''/* SPDX-License-Identifier: MIT */
#ifndef NATIVE_ADRENO_A730_HWINIT_H
#define NATIVE_ADRENO_A730_HWINIT_H
#include <stdint.h>
/* Generated by tools/gen-a730-hwinit.py. Do not edit by hand.
 *
 * The register/value facts come from the upstream msm driver's a6xx_catalog.c
 * (a730_hwcg[], a730_protect_regs[], GPL-2.0-only); the offsets are dword
 * register indices, and the protect encoding below is the hardware's
 * CP_PROTECT_REG layout, not upstream text.  Use these tables the way
 * a6xx_set_hwcg()/a6xx_set_cp_protect() use them; a730 is a7xx and its own
 * tables are authoritative (the a740 ones differ). */

/* HWCG: write each {offset, value} in order, then RBBM_CLOCK_CNTL (the last
 * entry) is what a6xx_set_hwcg() also writes as clock_cntl_on. */
static const uint32_t NativeAdrenoA730Hwcg[][2] = {
%s
};
#define NATIVE_ADRENO_A730_HWCG_COUNT %d

/* CP protect, in a6xx_set_cp_protect() write order: {CP_PROTECT index, value}.
 * The value is ADDR_START | (span << 18) | (nordwr << 31) - the exact bit
 * pattern upstream writes for each A6XX_PROTECT_* macro call.  Indices 45 and
 * 46 are the two all-zero upstream slots and are intentionally not written;
 * index 47 is the last span, whose end field CP_PROTECT_CNTL's
 * LAST_SPAN_INF_RANGE makes irrelevant. */
static const uint32_t NativeAdrenoA730Protect[][2] = {
%s
};
#define NATIVE_ADRENO_A730_PROTECT_COUNT %d
/* CP_PROTECT_CNTL: ACCESS_PROT_EN | ACCESS_FAULT_ON_VIOL_EN | LAST_SPAN_INF_RANGE. */
#define NATIVE_ADRENO_A730_PROTECT_CNTL 0x7u
#define NATIVE_ADRENO_A730_CP_PROTECT_CNTL 0x0084f
#define NATIVE_ADRENO_A730_CP_PROTECT_STATUS 0x00824
#define NATIVE_ADRENO_A730_CP_PROTECT 0x00850
#define NATIVE_ADRENO_A730_RBBM_CLOCK_CNTL 0x000ae
#endif
'''


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else '/Users/qprs/liuqin-build3/xnu/iokit/NativeAdreno/NativeAdrenoA730HwInit.h'
    hwcg = read_hwcg()
    protect = read_protect()

    rows = []
    for off, value, name in hwcg:
        rows.append('    {0x%05x,0x%08x},   /* %s */' % (off, value, re.sub(r'^REG_(A6XX_|A7XX_)?', '', name)))
    rows = [r.replace('{0x000ae,', '{0x000ae,') for r in rows]
    hwcg_txt = '\n'.join(rows)

    prows = []
    for i, value, text in protect:
        prows.append('    {%2d,0x%08x},   /* %s */' % (i, value, text))
    protect_txt = '\n'.join(prows)

    with open(out_path, 'w') as f:
        f.write(HEADER % (hwcg_txt, len(hwcg), protect_txt, len(protect)))
    print('%s: %u hwcg, %u protect' % (out_path, len(hwcg), len(protect)))


if __name__ == '__main__':
    main()
